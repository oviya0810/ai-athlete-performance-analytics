import React, { useState } from 'react';
import { AssessmentResult } from '../../types';
import jsPDF from 'jspdf';
import { FileBarChart, Download } from 'lucide-react';

interface ScoutingReportPanelProps {
  assessments: AssessmentResult[];
  coachName: string;
}

export const ScoutingReportPanel: React.FC<ScoutingReportPanelProps> = ({ assessments, coachName }) => {
  const uniqueAthletes = Array.from(new Map(assessments.map((a) => [a.athleteId, a])).values());
  const [selectedId, setSelectedId] = useState(uniqueAthletes[0]?.athleteId || '');
  const [comments, setComments] = useState('');

  const athleteAssessments = assessments.filter((a) => a.athleteId === selectedId);
  const athlete = athleteAssessments[0];

  const generatePDF = () => {
    if (!athlete) return;
    const doc = new jsPDF();

    doc.setFontSize(18);
    doc.text('SAI Talent Scouting Report', 14, 20);
    doc.setFontSize(10);
    doc.text(`Generated by: ${coachName}  •  ${new Date().toLocaleDateString('en-IN')}`, 14, 27);

    doc.setDrawColor(200);
    doc.line(14, 31, 196, 31);

    doc.setFontSize(13);
    doc.text(`Athlete: ${athlete.athleteName}`, 14, 42);
    doc.setFontSize(10);
    doc.text(`District/State: ${athlete.athleteDistrict}, ${athlete.athleteState}`, 14, 49);
    doc.text(`Talent Score: ${athlete.talentScore} / 100`, 14, 56);

    let y = 68;
    doc.setFontSize(12);
    doc.text('Assessment History', 14, y);
    y += 8;
    doc.setFontSize(9);
    athleteAssessments.forEach((a) => {
      doc.text(
        `${a.uploadDate}  |  ${a.testType.replace('_', ' ').toUpperCase()}  |  Score: ${a.talentScore}  |  Form: ${a.metricsBreakdown.form}%  |  Status: ${a.status.replace('_', ' ')}`,
        14,
        y
      );
      y += 6;
      if (y > 270) {
        doc.addPage();
        y = 20;
      }
    });

    y += 6;
    doc.setFontSize(12);
    doc.text('Metrics Breakdown (Latest)', 14, y);
    y += 8;
    doc.setFontSize(9);
    const mb = athlete.metricsBreakdown;
    [`Strength: ${mb.strength}%`, `Power: ${mb.power}%`, `Agility: ${mb.agility}%`, `Endurance: ${mb.endurance}%`, `Form: ${mb.form}%`].forEach((line) => {
      doc.text(line, 14, y);
      y += 6;
    });

    if (comments.trim()) {
      y += 6;
      doc.setFontSize(12);
      doc.text("Coach's Scouting Comments", 14, y);
      y += 8;
      doc.setFontSize(9);
      const split = doc.splitTextToSize(comments, 180);
      doc.text(split, 14, y);
    }

    doc.save(`Scouting_Report_${athlete.athleteName.replace(/\s+/g, '_')}.pdf`);
  };

  return (
    <div className="space-y-6 max-w-3xl">
      <div>
        <span className="px-3 py-1 rounded-full text-[10px] font-bold uppercase tracking-wider bg-purple-500/15 text-purple-300 border border-purple-500/30">
          Coach Tools • Scouting Report Generator
        </span>
        <h1 className="text-2xl sm:text-3xl font-black text-white mt-2 font-['Outfit'] flex items-center gap-2">
          <FileBarChart className="w-7 h-7 text-purple-300" />
          Scouting Report Generator
        </h1>
        <p className="text-xs sm:text-sm text-slate-300 mt-1">
          Auto-compile an athlete's assessment history into a downloadable PDF for SAI submission.
        </p>
      </div>

      <div className="glass-card rounded-3xl p-6 border border-slate-800 space-y-4">
        <select
          value={selectedId}
          onChange={(e) => setSelectedId(e.target.value)}
          className="w-full px-4 py-2.5 rounded-xl bg-slate-900 border border-slate-700 text-sm text-white"
        >
          {uniqueAthletes.map((a) => (
            <option key={a.athleteId} value={a.athleteId}>{a.athleteName} — {a.athleteDistrict}, {a.athleteState}</option>
          ))}
        </select>

        {athlete && (
          <div className="grid grid-cols-2 sm:grid-cols-5 gap-3">
            {[
              ['Strength', athlete.metricsBreakdown.strength],
              ['Power', athlete.metricsBreakdown.power],
              ['Agility', athlete.metricsBreakdown.agility],
              ['Endurance', athlete.metricsBreakdown.endurance],
              ['Form', athlete.metricsBreakdown.form]
            ].map(([label, val]) => (
              <div key={label as string} className="p-3 rounded-xl bg-slate-900/70 border border-slate-800 text-center">
                <div className="text-lg font-black text-white font-['Outfit']">{val}%</div>
                <span className="text-[10px] text-slate-500">{label}</span>
              </div>
            ))}
          </div>
        )}

        <textarea
          value={comments}
          onChange={(e) => setComments(e.target.value)}
          placeholder="Add your scouting comments/recommendation (optional)..."
          rows={4}
          className="w-full px-4 py-2.5 rounded-xl bg-slate-900 border border-slate-700 text-sm text-white"
        />

        <button
          onClick={generatePDF}
          disabled={!athlete}
          className="px-6 py-3 rounded-xl bg-purple-600 hover:bg-purple-500 disabled:opacity-50 text-white font-bold text-xs flex items-center gap-2"
        >
          <Download className="w-4 h-4" /> Download Scouting Report PDF
        </button>
      </div>
    </div>
  );
};
